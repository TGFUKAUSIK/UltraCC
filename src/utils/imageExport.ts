// DOM executor (browser-only)

/** Rasterize an ImageDoc to a PNG blob. Returns null when canvas is unavailable. */
export async function renderImageDoc(doc: ImageDoc, scale = 2): Promise<Blob | null> {
  const canvas = document.createElement('canvas');
  canvas.width = doc.width * scale;
  canvas.height = doc.height * scale;
  const ctx = canvas.getContext('2d');
  if (!ctx) return null;
  ctx.scale(scale, scale);
  ctx.fillStyle = '#ffffff';
  ctx.fillRect(0, 0, doc.width, doc.height);

  for (const c of doc.commands) {
    if (c.kind === 'rect') {
      ctx.fillStyle = c.fill;
      if (c.r) {
        const r = Math.min(c.r, c.w / 2, c.h / 2);
        ctx.beginPath();
        ctx.moveTo(c.x + r, c.y);
        ctx.arcTo(c.x + c.w, c.y, c.x + c.w, c.y + c.h, r);
        ctx.arcTo(c.x + c.w, c.y + c.h, c.x, c.y + c.h, r);
        ctx.arcTo(c.x, c.y + c.h, c.x, c.y, r);
        ctx.arcTo(c.x, c.y, c.x + c.w, c.y, r);
        ctx.closePath();
        ctx.fill();
      } else {
        ctx.fillRect(c.x, c.y, c.w, c.h);
      }
    } else if (c.kind === 'line') {
      ctx.strokeStyle = c.color;
      ctx.lineWidth = c.width ?? 1;
      ctx.beginPath();
      ctx.moveTo(c.x1, c.y1);
      ctx.lineTo(c.x2, c.y2);
      ctx.stroke();
    } else {
      const font = `${c.weight} ${c.size}px 'Segoe UI', system-ui, -apple-system, sans-serif`;
      if (c.mono) ctx.font = `${c.weight} ${c.size}px ui-monospace, monospace`;
      else ctx.font = font;
      ctx.fillStyle = c.color;
      ctx.textAlign = c.align ?? 'left';
      ctx.textBaseline = 'alphabetic';
      ctx.fillText(c.text, c.x, c.y);
    }
  }

  return await new Promise<Blob | null>((resolve) => canvas.toBlob((blob) => resolve(blob), 'image/png'));
}

/** Trigger a browser download for an image blob. */
export function downloadImageBlob(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 5000);
}

async function exportDoc(doc: ImageDoc, filename: string): Promise<void> {
  const blob = await renderImageDoc(doc);
  if (blob) downloadImageBlob(blob, filename);
}

