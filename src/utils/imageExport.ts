/**
 * imageExport.ts — shareable PNG export for timetable / attendance / exams.
 *
 * Zero new dependencies: a pure layout core turns dataset rows into an
 * `ImageDoc` (a list of draw commands), and a small DOM executor rasterizes
 * it onto a canvas and triggers a PNG download. The layout core is fully
 * unit-testable without a canvas.
 *
 * PRIVACY: the image contains ONLY what the caller passes. No credentials,
 * no session tokens, no VTOP identifiers beyond the rows themselves. The
 * registration number is included only when the caller explicitly passes it.
 */

import type { PrintableTimetableRow, PrintableAttendanceRow } from './printExport';
import { attendanceBandColor, attendanceColourKey } from './attendanceColour';
import { attendancePercentLabel } from './attendanceBands';

// ---------------------------------------------------------------------------
// Document model (pure)

export type ImageCommand =
  | { kind: 'rect'; x: number; y: number; w: number; h: number; fill: string; r?: number }
  | { kind: 'text'; x: number; y: number; text: string; size: number; weight: number; color: string; align?: 'left' | 'center' | 'right'; mono?: boolean }
  | { kind: 'line'; x1: number; y1: number; x2: number; y2: number; color: string; width?: number };

export interface ImageDoc {
  width: number;
  height: number;
  commands: ImageCommand[];
}

// ---------------------------------------------------------------------------
// Layout constants (light theme — reads well when shared over WhatsApp)

export const CANVAS_W = 900;
const MARGIN = 36;
const ACCENT_H = 6;
const HEADER_H = 78;
const FOOTER_H = 48;
const ROW_H = 28;
const SECTION_H = 44;
const COL_PAD = 8;

const COLOR_TEXT = '#111827';
const COLOR_SUB = '#6b7280';
const COLOR_FOOT = '#9ca3af';
const COLOR_ACCENT = '#2563eb';
const COLOR_ROW_LINE = '#e5e7eb';
const COLOR_HEADER_BG = '#f0f4f8';
const COLOR_ZEBRA = '#f9fafb';

// ---------------------------------------------------------------------------

/** Estimate visible width of text (canvas-free). ~0.58 × font-size per char. */
export function estimatedTextWidth(text: string, size: number): number {
  return text.length * size * 0.58;
}

/** Truncate with an ellipsis to fit an estimated pixel width. */
export function truncateToWidth(text: string, maxWidth: number, size: number): string {
  if (estimatedTextWidth(text, size) <= maxWidth) return text;
  const ell = '…';
  const per = size * 0.58;
  const keep = Math.max(0, Math.floor(maxWidth / per) - 1);
  return keep <= 0 ? ell : `${text.slice(0, keep)}${ell}`;
}

/** Escape-free single-line cell text. */
function cellText(value: string | undefined | null): string {
  return (value ?? '').toString();
}

// ---------------------------------------------------------------------------

interface Builder {
  commands: ImageCommand[];
  y: number;
}

function pushHeader(b: Builder, title: string, subtitle: string): void {
  const inner = CANVAS_W - MARGIN * 2;
  b.commands.push({ kind: 'rect', x: 0, y: 0, w: CANVAS_W, h: ACCENT_H, fill: COLOR_ACCENT });
  b.commands.push({ kind: 'text', x: MARGIN, y: MARGIN + 20, text: title, size: 24, weight: 800, color: COLOR_TEXT });
  b.commands.push({ kind: 'text', x: MARGIN, y: MARGIN + 44, text: subtitle, size: 12, weight: 500, color: COLOR_SUB });
  b.y = HEADER_H;
  b.commands.push({ kind: 'line', x1: MARGIN, y1: b.y - 14, x2: MARGIN + inner, y2: b.y - 14, color: COLOR_ROW_LINE });
}

function pushFooter(b: Builder, commands: ImageCommand[]): void {
  const y = b.y + 34;
  commands.push({ kind: 'text', x: MARGIN, y, text: 'Generated by UltraCC — VIT Chennai student portal', size: 11, weight: 500, color: COLOR_FOOT });
  commands.push({ kind: 'text', x: CANVAS_W - MARGIN, y, text: new Date().toLocaleDateString('en-IN'), size: 11, weight: 500, color: COLOR_FOOT, align: 'right' });
  commands.push({ kind: 'line', x1: MARGIN, y1: y - 22, x2: CANVAS_W - MARGIN, y2: y - 22, color: COLOR_ROW_LINE });
}

interface Column<T> {
  header: string;
  width: number;
  align?: 'left' | 'center' | 'right';
  cell: (row: T) => string;
  color?: (row: T) => string;
  weight?: (row: T) => number;
}

/** Push a full-width table section into the doc. */
function pushTable<T>(b: Builder, cols: Column<T>[], rows: T[]): void {
  const inner = CANVAS_W - MARGIN * 2;
  const colWidths = cols.map((c) => (c.width / 100) * inner);

  // Header row
  b.commands.push({ kind: 'rect', x: MARGIN, y: b.y, w: inner, h: ROW_H, fill: COLOR_HEADER_BG });
  let x = MARGIN + COL_PAD;
  cols.forEach((c, i) => {
    b.commands.push({
      kind: 'text', x: c.align === 'right' ? x + colWidths[i] - COL_PAD * 2 : c.align === 'center' ? x + colWidths[i] / 2 - COL_PAD : x,
      y: b.y + 18, text: c.header.toUpperCase(), size: 10, weight: 700, color: COLOR_SUB, align: c.align === 'right' ? 'right' : c.align === 'center' ? 'center' : 'left',
    });
    x += colWidths[i];
  });
  b.y += ROW_H;

  // Body rows
  rows.forEach((row, rIdx) => {
    if (rIdx % 2 === 1) {
      b.commands.push({ kind: 'rect', x: MARGIN, y: b.y, w: inner, h: ROW_H, fill: COLOR_ZEBRA });
    }
    let cx = MARGIN + COL_PAD;
    cols.forEach((c, i) => {
      const maxW = colWidths[i] - COL_PAD * 2;
      const text = truncateToWidth(cellText(c.cell(row)), maxW, 12);
      const alignX = c.align === 'right' ? cx + maxW : c.align === 'center' ? cx + maxW / 2 : cx;
      b.commands.push({
        kind: 'text', x: alignX, y: b.y + 18, text, size: 12,
        weight: c.weight ? c.weight(row) : 400,
        color: c.color ? c.color(row) : COLOR_TEXT,
        align: c.align,
      });
      cx += colWidths[i];
    });
    b.y += ROW_H;
  });
}

// ---------------------------------------------------------------------------

export interface ImageExportMeta {
  regNo?: string;
  /** Subtitle suffix, e.g. semester. */
  context?: string;
}

function baseSubtitle(meta: ImageExportMeta): string {
  const parts: string[] = [];
  if (meta.regNo) parts.push(`Reg. No ${meta.regNo}`);
  if (meta.context) parts.push(meta.context);
  return parts.length ? `${parts.join(' · ')} · Generated` : 'Generated';
}

/** Weekly timetable PNG (grouped MON–SAT like the PDF export). */
export function buildTimetableImageDoc(rows: PrintableTimetableRow[], meta: ImageExportMeta = {}): ImageDoc {
  const commands: ImageCommand[] = [];
  const b: Builder = { commands, y: 0 };
  pushHeader(b, 'Weekly Timetable', baseSubtitle(meta));

  const days = ['MON', 'TUE', 'WED', 'THU', 'FRI', 'SAT'];
  const byDay = new Map<string, PrintableTimetableRow[]>();
  for (const r of rows) {
    const day = r.day.toUpperCase().slice(0, 3);
    if (!days.includes(day)) continue;
    if (!byDay.has(day)) byDay.set(day, []);
    byDay.get(day)!.push(r);
  }

  const cols: Column<PrintableTimetableRow>[] = [
    { header: 'Time', width: 15, cell: (r) => `${r.startTime}–${r.endTime}`, weight: () => 700 },
    { header: 'Course', width: 12, cell: (r) => r.courseCode, weight: () => 700 },
    { header: 'Title', width: 28, cell: (r) => r.courseTitle },
    { header: 'Slot', width: 8, align: 'center', cell: (r) => r.slot },
    { header: 'Venue', width: 14, cell: (r) => r.venue },
    { header: 'Faculty', width: 16, cell: (r) => r.faculty },
    { header: 'Type', width: 7, align: 'center', cell: (r) => (r.isLab ? 'Lab' : 'Theory'), color: (r) => (r.isLab ? '#7c3aed' : COLOR_TEXT) },
  ];

  for (const day of days) {
    const dayRows = byDay.get(day);
    if (!dayRows?.length) continue;
    b.commands.push({ kind: 'text', x: MARGIN, y: b.y + 26, text: day, size: 14, weight: 800, color: COLOR_ACCENT });
    b.y += SECTION_H - 10;
    pushTable(b, cols, dayRows.slice().sort((a, c) => a.startTime.localeCompare(c.startTime)));
    b.y += 10;
  }

  if (!rows.length) {
    commands.push({ kind: 'text', x: MARGIN, y: b.y + 26, text: 'No classes on this timetable.', size: 12, weight: 500, color: COLOR_SUB });
    b.y += ROW_H;
  }

  pushFooter(b, commands);
  return { width: CANVAS_W, height: b.y + FOOTER_H, commands };
}

/** Attendance summary PNG, worst courses first. */
export function buildAttendanceImageDoc(rows: PrintableAttendanceRow[], meta: ImageExportMeta = {}): ImageDoc {
  const commands: ImageCommand[] = [];
  const b: Builder = { commands, y: 0 };
  const overall = rows.length
    ? (rows.reduce((s, r) => s + r.attended, 0) / Math.max(1, rows.reduce((s, r) => s + r.total, 0))) * 100
    : undefined;
  const parts: string[] = [];
  if (meta.regNo) parts.push(`Reg. No ${meta.regNo}`);
  if (overall !== undefined) parts.push(`Overall ${attendancePercentLabel(overall)}%`);
  const subtitle = parts.length ? `${parts.join(' · ')} · Generated` : 'Generated';
  pushHeader(b, 'Attendance Report', subtitle);

  const cols: Column<PrintableAttendanceRow>[] = [
    { header: 'Course', width: 13, cell: (r) => r.courseCode, weight: () => 700 },
    { header: 'Title', width: 37, cell: (r) => r.courseTitle },
    { header: 'Attended', width: 12, align: 'center', cell: (r) => `${r.attended}/${r.total}` },
    { header: '%', width: 10, align: 'center', cell: (r) => `${attendancePercentLabel(r.percentage)}%`, color: (r) => attendanceBandColor(r.percentage), weight: () => 700 },
    { header: 'Faculty', width: 28, cell: (r) => r.faculty },
  ];

  pushTable(b, cols, rows.slice().sort((a, c) => a.percentage - c.percentage));
  // The coloured column is a claim, so the image states the scale it was drawn
  // on — a recipient with no app open cannot otherwise tell 79% "amber" from
  // 79% "below the bar this student set".
  b.y += 8;
  commands.push({ kind: 'text', x: MARGIN, y: b.y + 14, text: attendanceColourKey(), size: 11, weight: 500, color: COLOR_SUB });
  b.y += 22;
  pushFooter(b, commands);
  return { width: CANVAS_W, height: b.y + FOOTER_H, commands };
}

/** Minimal exam row — mirrors the fields shown in the exam schedule UI. */
export interface PrintableExamRow {
  courseCode: string;
  courseTitle: string;
  examType: string;
  date: string;
  time: string;
  venue: string;
  seatNo: string;
}

/** Exam schedule PNG (date, time, venue, seat). */
export function buildExamsImageDoc(rows: PrintableExamRow[], meta: ImageExportMeta = {}): ImageDoc {
  const commands: ImageCommand[] = [];
  const b: Builder = { commands, y: 0 };
  pushHeader(b, 'Exam Schedule', baseSubtitle(meta));

  const cols: Column<PrintableExamRow>[] = [
    { header: 'Date', width: 13, cell: (r) => (r.date ? r.date.slice(0, 10) : ''), weight: () => 700 },
    { header: 'Time', width: 11, cell: (r) => r.time },
    { header: 'Exam', width: 10, align: 'center', cell: (r) => r.examType, color: () => COLOR_ACCENT, weight: () => 700 },
    { header: 'Course', width: 34, cell: (r) => (r.courseTitle ? `${r.courseCode} — ${r.courseTitle}` : r.courseCode), weight: () => 700 },
    { header: 'Venue', width: 19, cell: (r) => r.venue },
    { header: 'Seat', width: 13, align: 'center', cell: (r) => r.seatNo },
  ];

  pushTable(b, cols, rows);
  pushFooter(b, commands);
  return { width: CANVAS_W, height: b.y + FOOTER_H, commands };
}

