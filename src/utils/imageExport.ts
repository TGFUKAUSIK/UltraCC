// FFCS plan export — the user's hypothetical course plan (plan-only data;
// no VTOP, no credentials, nothing session-derived by construction).

/** Minimal FFCS plan row — mirrors the plan list in the planner UI. */
export interface PrintableFfcsPlanRow {
  code: string;
  title: string;
  slot: string;
  type: string;
  venue: string;
  faculty: string;
  credits: number | null;
  /** Sections flagged as clashing render in red. */
  clashes: boolean;
}

/** FFCS plan PNG (course list + credits total). */
export function buildFfcsPlanImageDoc(rows: PrintableFfcsPlanRow[], meta: ImageExportMeta & { creditsTotal?: number } = {}): ImageDoc {
  const commands: ImageCommand[] = [];
  const b: Builder = { commands, y: 0 };
  const parts: string[] = [];
  if (meta.creditsTotal !== undefined) parts.push(`${rows.length} course${rows.length === 1 ? '' : 's'} · ${meta.creditsTotal} credits`);
  if (meta.context) parts.push(meta.context);
  pushHeader(b, 'FFCS Plan', parts.length ? `${parts.join(' · ')} · Generated` : 'Generated');

  const cols: Column<PrintableFfcsPlanRow>[] = [
    { header: 'Course', width: 13, cell: (r) => r.code, weight: () => 700 },
    { header: 'Title', width: 30, cell: (r) => r.title },
    { header: 'Slot', width: 10, align: 'center', cell: (r) => r.slot },
    { header: 'Type', width: 7, align: 'center', cell: (r) => r.type },
    { header: 'Venue', width: 12, cell: (r) => r.venue },
    { header: 'Faculty', width: 18, cell: (r) => r.faculty },
    { header: 'Cr', width: 5, align: 'center', cell: (r) => (r.credits == null ? '—' : String(r.credits)) },
  ];
  if (rows.some((r) => r.clashes)) {
    cols.push({ header: '⚠', width: 5, align: 'center', cell: (r) => (r.clashes ? 'CLASH' : ''), color: (r) => (r.clashes ? '#b91c1c' : COLOR_TEXT), weight: (r) => (r.clashes ? 700 : 400) });
  }
  const clashColor = '#b91c1c';
  const baseCols = cols.slice(0, 7);
  const withClashColor = (c: Column<PrintableFfcsPlanRow>, idx: number): Column<PrintableFfcsPlanRow> => ({
    ...c,
    color: (r) => (r.clashes && idx < 7 ? clashColor : c.color ? c.color(r) : COLOR_TEXT),
  });
  pushTable(b, cols.map((c, i) => (rows.some((r) => r.clashes) && i < 7 ? withClashColor(c, i) : c)), rows);
  pushFooter(b, commands);
  return { width: CANVAS_W, height: b.y + FOOTER_H, commands };
}

export function exportFfcsPlanImage(rows: PrintableFfcsPlanRow[], meta: ImageExportMeta & { creditsTotal?: number } = {}): void {
  void exportDoc(buildFfcsPlanImageDoc(rows, meta), 'ultracc-ffcs-plan.png');
}
