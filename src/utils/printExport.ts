/**
 * printExport.ts — print-to-PDF / image export utilities.
 *
 * Print/PDF and PNG exports without adding data or redesigning UI:
 * opens a clean, print-styled window containing the student's schedule and
 * triggers the browser's print dialog (Save as PDF). Also offers a PNG
 * snapshot of the same content via canvas rasterization.
 *
 * No VTOP data is invented here — callers pass their already-loaded records.
 */

// ---------------------------------------------------------------------------

export interface PrintableTimetableRow {
  day: string;
  startTime: string;
  endTime: string;
  courseCode: string;
  courseTitle: string;
  slot: string;
  venue: string;
  faculty: string;
  isLab: boolean;
}

export interface PrintableAttendanceRow {
  courseCode: string;
  courseTitle: string;
  attended: number;
  total: number;
  percentage: number;
  faculty: string;
}

// ---------------------------------------------------------------------------

function openPrintWindow(title: string): Window | null {
  const win = window.open('', '_blank', 'width=900,height=700');
  if (!win) return null;
  win.document.write(`<!doctype html>
<html>
<head>
<meta charset="utf-8" />
<title>${title}</title>
<style>
  * { box-sizing: border-box; }
  body { font-family: 'Segoe UI', system-ui, -apple-system, sans-serif; margin: 24px; color: #111; }
  h1 { font-size: 18px; margin: 0 0 2px; }
  .sub { font-size: 11px; color: #666; margin-bottom: 18px; }
  table { width: 100%; border-collapse: collapse; margin-bottom: 22px; }
  th, td { border: 1px solid #ccc; padding: 6px 8px; font-size: 11px; text-align: left; }
  th { background: #f0f4f8; font-size: 10px; text-transform: uppercase; letter-spacing: 0.04em; }
  .section { font-size: 13px; font-weight: 700; margin: 18px 0 8px; }
  .footer { margin-top: 20px; font-size: 10px; color: #999; border-top: 1px solid #ddd; padding-top: 8px; }
  .risk { color: #b91c1c; font-weight: 700; }
  .warn { color: #b45309; font-weight: 600; }
  .ok { color: #15803d; }
  @media print { body { margin: 12mm; } .noprint { display: none; } }
</style>
</head>
<body>`);
  return win;
}

function finishPrintWindow(win: Window, footer: string): void {
  win.document.write(`
<div class="footer">${footer}</div>
</body>
</html>`);
  win.document.close();
  win.focus();
  // Give the browser a tick to layout before opening the print dialog.
  setTimeout(() => win.print(), 250);
}

