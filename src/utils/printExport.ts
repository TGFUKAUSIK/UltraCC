/**
 * Export the weekly timetable as a print-ready document (Save as PDF).
 */
export function exportTimetableToPdf(
  rows: PrintableTimetableRow[],
  meta: { regNo?: string; semester?: string },
): void {
  if (!rows.length) return;
  const win = openPrintWindow('UltraCC — Weekly Timetable');
  if (!win) return;

  const days = ['MON', 'TUE', 'WED', 'THU', 'FRI', 'SAT'];
  const byDay = new Map<string, PrintableTimetableRow[]>();
  for (const r of rows) {
    const day = r.day.toUpperCase().slice(0, 3);
    if (!days.includes(day)) continue;
    if (!byDay.has(day)) byDay.set(day, []);
    byDay.get(day)!.push(r);
  }

  win.document.write(`
<div class="noprint" style="margin-bottom:14px;font-size:11px;color:#555">Use your browser's print dialog to save as PDF.</div>
<h1>Weekly Timetable</h1>
<div class="sub">${meta.regNo ? `Reg. No: ${meta.regNo} · ` : ''}${meta.semester ? `Semester: ${escapeHtml(meta.semester)} · ` : ''}Generated ${new Date().toLocaleDateString()}</div>`);

  for (const day of days) {
    const dayRows = byDay.get(day);
    if (!dayRows?.length) continue;
    win.document.write(`<div class="section">${day}</div><table><thead><tr><th>Time</th><th>Course</th><th>Title</th><th>Slot</th><th>Venue</th><th>Faculty</th><th>Type</th></tr></thead><tbody>`);
    for (const r of dayRows.sort((a, b) => a.startTime.localeCompare(b.startTime))) {
      win.document.write(`<tr>
<td>${escapeHtml(`${r.startTime}–${r.endTime}`)}</td>
<td><strong>${escapeHtml(r.courseCode)}</strong></td>
<td>${escapeHtml(r.courseTitle)}</td>
<td>${escapeHtml(r.slot)}</td>
<td>${escapeHtml(r.venue)}</td>
<td>${escapeHtml(r.faculty)}</td>
<td>${r.isLab ? 'Lab' : 'Theory'}</td>
</tr>`);
    }
    win.document.write('</tbody></table>');
  }

  finishPrintWindow(win, 'Generated by UltraCC — VIT Chennai student portal');
}

/**
 * Export attendance as a print-ready one-pager (Save as PDF).
 */
export function exportAttendanceToPdf(
  rows: PrintableAttendanceRow[],
  meta: { overall?: number; regNo?: string },
): void {
  if (!rows.length) return;
  const win = openPrintWindow('UltraCC — Attendance Report');
  if (!win) return;

  win.document.write(`
<div class="noprint" style="margin-bottom:14px;font-size:11px;color:#555">Use your browser's print dialog to save as PDF.</div>
<h1>Attendance Report</h1>
<div class="sub">${meta.regNo ? `Reg. No: ${meta.regNo} · ` : ''}${meta.overall !== undefined ? `Overall: ${meta.overall}% · ` : ''}Generated ${new Date().toLocaleDateString()}</div>
<table>
<thead><tr><th>Course</th><th>Title</th><th>Attended</th><th>Total</th><th>%</th><th>Faculty</th></tr></thead>
<tbody>`);
  for (const r of rows.sort((a, b) => a.percentage - b.percentage)) {
    const cls = r.percentage < 75 ? 'risk' : r.percentage < 85 ? 'warn' : 'ok';
    win.document.write(`<tr>
<td><strong>${escapeHtml(r.courseCode)}</strong></td>
<td>${escapeHtml(r.courseTitle)}</td>
<td>${r.attended}</td>
<td>${r.total}</td>
<td class="${cls}">${r.percentage}%</td>
<td>${escapeHtml(r.faculty)}</td>
</tr>`);
  }
  win.document.write('</tbody></table>');
  finishPrintWindow(win, 'Generated by UltraCC — VIT Chennai student portal');
}

// ---------------------------------------------------------------------------

function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}
