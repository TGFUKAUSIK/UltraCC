/**
 * The printable payment receipt, as one self-contained HTML document.
 *
 * Every field comes from VTOP, which is an upstream this app does not control.
 * The document is written into a same-origin window, so an unescaped `<script>`
 * in any field would run with the student's storage — their cached marks and
 * ride/study-group tokens — in reach. All values are therefore escaped, not
 * formatted: this is output encoding at the sink, the correct protection here.
 */

import type { ReceiptRecord } from '../lib/vtop/types';

const ESCAPES: Record<string, string> = {
  '&': '&amp;',
  '<': '&lt;',
  '>': '&gt;',
  '"': '&quot;',
  "'": '&#39;',
};

export function escapeHtml(value: unknown): string {
  return String(value ?? '').replace(/[&<>"']/g, (ch) => ESCAPES[ch]);
}

export function receiptHtml(receipt: ReceiptRecord, printedOn: Date = new Date()): string {
  const cell = (value: unknown) => escapeHtml(value);
  return `<!DOCTYPE html><html><head><title>Receipt ${cell(receipt.receiptNumber)}</title><style>body{font-family:system-ui;padding:40px;background:#000;color:#fff}table{width:100%;border-collapse:collapse}td,th{padding:8px 12px;border-bottom:1px solid #333;text-align:left}th{color:#888;font-size:11px;text-transform:uppercase}.amount{color:#34d399;font-size:20px;font-weight:bold}.header{text-align:center;margin-bottom:30px}.header h1{font-size:24px;margin:0}.header p{color:#888;font-size:12px}@media print{body{background:#fff;color:#000}}</style></head><body><div class='header'><h1>UltraCC — Payment Receipt</h1><p>VIT Chennai Fee Payment Receipt</p></div><table><tr><th>Receipt Number</th><td>${cell(receipt.receiptNumber)}</td></tr><tr><th>Date</th><td>${cell(receipt.date)}</td></tr><tr><th>Amount</th><td class='amount'>${cell(receipt.amount)}</td></tr><tr><th>Campus</th><td>${cell(receipt.campusCode)}</td></tr><tr><th>Registration No</th><td>${cell(receipt.regno)}</td></tr><tr><th>Application No</th><td>${cell(receipt.applno)}</td></tr></table><p style='margin-top:30px;text-align:center;color:#666;font-size:10px'>Generated by UltraCC • ${cell(printedOn.toLocaleDateString('en-IN'))}</p></body></html>`;
}
