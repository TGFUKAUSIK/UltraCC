function stripTags(html: string): string {
  return html.replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim();
}

/** Text of the <span> that follows the given icon (non-greedy, first hit). */
function textAfterIcon(block: string, iconRe: RegExp): string {
  const m = block.match(iconRe);
  if (!m || m.index === undefined) return '';
  const after = block.slice(m.index + m[0].length);
  const span = after.match(/<span\b[^>]*>([\s\S]*?)<\/span>/i);
  return span ? stripTags(span[1]) : '';
}

/**
 * Parse EventHub cards. Live structure (verified against
 * eventhubcc.vit.ac.in/EventHub, Bootstrap 5):
 *
 *   <div class="card text-center">
 *     <div class="card-body">
 *       <h3 class="card-title"><span>Title</span></h3>
 *       <div><i class="fa-solid fa-people-carry-box"></i><span>Eligibility</span></div>
 *       <div>(<span>Type</span>)</div>
 *       <div id="details"> … fa-calendar-days/fa-map-location-dot/
 *           fa-indian-rupee-sign icons, each followed by a <span> … </div>
 *       <button name="eid" value="1201" formaction="/EventHub/eventPreview">View</button>
 *     </div>
 *   </div>
 *
 * The card boundary is the NEXT `class="…card…"` div (or EOF) — never a
 * naive first `</div></div>` (that truncates before the button/eid).
 */
export function parseEvents(html: string): HubEvent[] {
  const out: HubEvent[] = [];
  const cardRe = /<div\b[^>]*class=["'][^"']*\bcard\b[^"']*["'][^>]*>/gi;
  const parts = html.split(cardRe);
  for (let i = 1; i < parts.length; i++) {
    const block = parts[i];
    const nextCard = block.search(/<div\b[^>]*class=["'][^"']*\bcard\b[^"']*["'][^>]*>/i);
    const body = nextCard >= 0 ? block.slice(0, nextCard) : block;

    const eid = body.match(/name=["']eid["'][^>]*value=["']([^"']+)["']/i)?.[1]
      || body.match(/value=["']([^"']+)["'][^>]*name=["']eid["']/i)?.[1] || '';
    const title = stripTags(body.match(/<h3\b[^>]*class=["'][^"']*card-title[^"']*["'][^>]*>([\s\S]*?)<\/h3>/i)?.[1] || '');
    if (!eid || !title) continue;

    const eligibility = textAfterIcon(body, /fa-(?:people-carry-box|user-large)/i);
    const date = textAfterIcon(body, /fa-calendar-days/i);
    const location = textAfterIcon(body, /fa-map-location-dot/i);
    const price = textAfterIcon(body, /fa-indian-rupee-sign/i);
    const type = body.match(/\(\s*<span\b[^>]*>([\s\S]*?)<\/span>\s*\)/i)?.[1]?.trim() || '';
    const registerUrlRaw = body.match(/formaction=["']([^"']+)["']/i)?.[1] || '';
    const registerUrl = registerUrlRaw
      ? (registerUrlRaw.startsWith('http') ? registerUrlRaw : ORIGIN + registerUrlRaw)
      : `${ORIGIN}/EventHub/`;

    let posterUrl = body.match(/<img\b[^>]*src=["']([^"']+)["']/i)?.[1] || '';
    if (!posterUrl) {
      posterUrl = body.match(/background(?:-image)?\s*:\s*url\(['"]?([^'")]+)['"]?\)/i)?.[1] || '';
    }
    if (posterUrl && !posterUrl.startsWith('http') && !posterUrl.startsWith('data:')) {
      posterUrl = posterUrl.startsWith('/') ? ORIGIN + posterUrl : `${ORIGIN}/EventHub/${posterUrl}`;
    }

    out.push({ eid, title, eligibility, type, date, location, price, posterUrl, registerUrl });
  }
  return out;
}

/** True for handshake rejections caused by an untrusted/rotated CA chain. */
function isTlsTrustError(err: unknown): boolean {
  const msg = err instanceof Error ? err.message : String(err);
  return /invalid peer certificate|unknown issuer|certificate verify failed/i.test(msg);
}

/** One fetch of the Event Hub page. Retries once on the default client if the
 *  pinned CA chain rejects the handshake — still fully verified, never
 *  acceptInvalidCerts — so a future Sectigo rotation degrades gracefully
 *  instead of bricking the feature. */
async function fetchEventHubPage(): Promise<Response> {
  const opts: RequestInit & { client?: unknown } = {
    headers: {
      'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126 Safari/537.36',
    },
  };
  if (httpClient) opts.client = httpClient;
  try {
    return await fetch(`${ORIGIN}/EventHub/`, opts);
  } catch (err) {
    if (httpClient && opts.client && isTlsTrustError(err)) {
      console.warn(`[event-hub] pinned CA chain rejected the handshake (${err instanceof Error ? err.message : String(err)}) — retrying on the default trust store`);
      const retry: RequestInit & { client?: unknown } = { ...opts };
      delete retry.client;
      return fetch(`${ORIGIN}/EventHub/`, retry as RequestInit);
    }
    throw err;
  }
}

Deno.serve(async (req: Request) => {
  if (req.method === 'OPTIONS') return new Response('ok', { headers: corsHeaders() });
  try {
    const res = await fetchEventHubPage();
    if (!res.ok) {
      console.warn(`[event-hub] upstream responded ${res.status}`);
      throw new Error(`Event Hub responded ${res.status}`);
    }
    const html = await res.text();
    const events = parseEvents(html);
    return new Response(JSON.stringify({ success: true, events, syncedAt: Date.now() }), {
      headers: { ...corsHeaders(), 'Content-Type': 'application/json' },
    });
  } catch (err: unknown) {
    // Raw transport errors (TLS chains, socket details, internal paths) are
    // logged server-side but never shipped to the UI. Clients get a single
    // friendly, stable string they can render as-is.
    console.error('[event-hub] fetch failed:', err instanceof Error ? err.message : String(err));
    return new Response(JSON.stringify({ success: false, error: 'Event Hub is temporarily unavailable. Please try again later.', events: [] }), {
      status: 200,
      headers: { ...corsHeaders(), 'Content-Type': 'application/json' },
    });
  }
});
